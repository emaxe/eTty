  ptyKill: (pid) => ipcRenderer.invoke(IPC_CHANNELS.PTY_KILL, pid),
  onPtyData: (cb) => onIPC(IPC_CHANNELS.PTY_DATA, (_, { pid, data }) => cb(pid, data)),
