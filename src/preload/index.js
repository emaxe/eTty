  fsCopyMany: (srcPaths, destDir, ctx) => ipcRenderer.invoke(IPC_CHANNELS.FS_COPY_MANY, { srcPaths, destDir, ctx }),
  fsMove: (srcPaths, destDir, ctx) => ipcRenderer.invoke(IPC_CHANNELS.FS_MOVE, { srcPaths, destDir, ctx }),
