  fsCreateFile: (filePath, ctx) => ipcRenderer.invoke(IPC_CHANNELS.FS_CREATE_FILE, { filePath, ctx }),
  fsCreateDir: (dirPath, ctx) => ipcRenderer.invoke(IPC_CHANNELS.FS_CREATE_DIR, { dirPath, ctx }),
